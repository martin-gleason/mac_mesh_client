// `C4-T6`, ported from `scripts/check_commit_msg.py`. Refuse a register ID in a commit subject.
//
// **Structural IDs appear in git; register IDs never do.** `C1`, `F1-T2`, `F4c` belong in a
// subject. `D5`, `RR8`, `M1`, `FR17` do not — they go in the body, where they are correct.
// Accepted false positives, recorded rather than fixed: `H264` and `O365` match the
// register-ID shape and nothing in a subject line tells them apart.

import Foundation

enum CommitMessage {
    static let registerID = try! NSRegularExpression(pattern: #"\b(?:NFR|FR|RR|[DOHMG])\d{1,3}\b"#)
    // The retrofit letter belongs to the feature, so it comes before the task: `F4c-T1`.
    static let conventional = try! NSRegularExpression(
        pattern: #"^(?:feat|fix|test|chore|docs|refactor|ci)\((?:[FC]\d{1,3}[a-z]?(?:-T\d{1,3})?)\): .+"#)
    // `git revert` and `git merge` write these; refusing them is how a gate gets bypassed.
    static let generated = try! NSRegularExpression(
        pattern: #"^(?:Revert ".*"|Merge (?:branch|pull request|remote-tracking) .*)$"#)

    static func main(_ args: [String]) -> Int32 {
        guard let path = args.first, let text = try? String(contentsOfFile: path, encoding: .utf8) else {
            return fail("usage: harness commit-msg <path to commit message>")
        }
        let subject = text.components(separatedBy: "\n")
            .first { !$0.trimmingCharacters(in: .whitespaces).isEmpty && !$0.hasPrefix("#") } ?? ""
        guard !subject.isEmpty else { return fail("\ncommit-msg: REFUSED — the message has no subject line.\n") }

        let range = NSRange(subject.startIndex..., in: subject)
        if generated.firstMatch(in: subject, range: range) != nil {
            print("commit-msg: pass (generated by git)")
            return 0
        }
        var problems: [String] = []
        for match in registerID.matches(in: subject, range: range) {
            let id = (subject as NSString).substring(with: match.range)
            problems.append("""
                  `\(id)` is a register ID and must not appear in a subject line.
                      Cite the F/C task that builds or closes it in the scope, and explain
                      it in the body — a register ID in the body is correct usage.
                """)
        }
        if conventional.firstMatch(in: subject, range: range) == nil {
            problems.append("""
                  the subject is not `<type>(<ID>): <description>`.
                      Types: feat fix test chore docs refactor ci.
                      The ID in the scope is structural: C1, F1, F1-T2, F4c.
                      Got: \(subject)
                """)
        }
        guard !problems.isEmpty else {
            print("commit-msg: pass")
            return 0
        }
        return fail("\ncommit-msg: REFUSED\n\n" + problems.joined(separator: "\n") + "\n")
    }
}
